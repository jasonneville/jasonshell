import { readFileSync, writeFileSync } from 'node:fs';

// Only root defaults and exact preset selectors are inputs. Preferences and
// component-local declarations must never accidentally become preset data.
const css = readFileSync(new URL('../src/app.css', import.meta.url), 'utf8');
const registry = readFileSync(new URL('../src/lib/themes.ts', import.meta.url), 'utf8');
const ids = [...registry.matchAll(/\{ id: '([^']+)', label:/g)].map((match) => match[1]);
if (ids.length !== 34 || new Set(ids).size !== 34) throw new Error('Expected 34 unique builtin themes');
const token = /^--js-(?:color-|shadow-|focus-ring$|inset-highlight$|scrollbar-|bg-|stack-editor-selection)/;
function declarations(body) {
  return Object.fromEntries([...body.matchAll(/(--js-[\w-]+)\s*:\s*([^;]+);/g)]
    .filter(([, name]) => token.test(name)).map(([, name, value]) => [name, value.trim()]));
}
const root = css.match(/^:root\s*\{([\s\S]*?)^\}/m)?.[1];
if (!root) throw new Error('Missing root defaults');
const defaults = declarations(root);
const required = [
  'color-bg', 'color-text', 'color-text-strong', 'color-text-muted', 'color-text-subtle',
  'color-surface', 'color-surface-raised', 'color-surface-sunken', 'color-surface-overlay',
  'color-control', 'color-control-hover', 'color-control-active', 'color-border', 'color-border-soft',
  'color-accent', 'color-accent-soft', 'color-accent-border', 'color-selected',
  'color-success', 'color-success-border', 'color-info', 'color-warning', 'color-warning-border',
  'color-error', 'color-error-border', 'color-error-text', 'shadow-raised', 'shadow-panel',
  'focus-ring', 'inset-highlight', 'bg-surface', 'bg-bar', 'bg-control', 'bg-active',
  'scrollbar-thumb', 'scrollbar-track', 'stack-editor-selection', 'stack-editor-selection-inactive'
].map((name) => `--js-${name}`);
for (const name of required) if (!(name in defaults)) throw new Error(`Missing shared palette token: ${name}`);
const palettes = Object.fromEntries(ids.map((id) => {
  const body = css.match(new RegExp(`:root\\[data-theme='${id}'\\]\\s*\\{([\\s\\S]*?)\\n\\}`))?.[1];
  if (body === undefined) throw new Error(`Missing exact selector: ${id}`);
  const palette = { ...defaults, ...declarations(body) };
  const visited = new Set();
  function visit(name, path = new Set()) {
    if (!(name in palette)) throw new Error(`Missing ${name} in ${id}`);
    if (path.has(name)) throw new Error(`Cyclic ${name} in ${id}`);
    if (visited.has(name)) return;
    const next = new Set([...path, name]);
    for (const [, ref] of palette[name].matchAll(/var\((--js-[\w-]+)\)/g)) visit(ref, next);
    visited.add(name);
  }
  Object.keys(palette).forEach((name) => visit(name));
  return [id, palette];
}));
const output = '// Generated by scripts/generate-theme-palettes.mjs. Do not edit.\n'
  + 'export const BUILTIN_THEME_PALETTES: Readonly<Record<string, Readonly<Record<string, string>>>> = Object.freeze(\n'
  + JSON.stringify(palettes, null, 2) + '\n);\n'
  + 'for (const palette of Object.values(BUILTIN_THEME_PALETTES)) Object.freeze(palette);\n';
const target = new URL('../src/lib/builtinThemePalettes.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Builtin palette data stale; run npm run themes:generate');
} else writeFileSync(target, output);
