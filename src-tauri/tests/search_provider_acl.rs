//! Tier 1 (PRD-02/03) RED: new search-activation commands must be registered and resolve through the
//! actual generated Tauri ACL for the top-bar webview (where search-row activation is processed),
//! and stay denied for unknown labels and remote origins. Uses the same generated inputs and
//! RuntimeAuthority as `shell_app_acl.rs`; no Builder, window, or shell startup.
use std::{collections::{BTreeMap, BTreeSet}, fs, path::PathBuf};
use tauri::{
    ipc::{Origin, RuntimeAuthority},
    utils::{
        acl::{capability::Capability, manifest::Manifest, resolved::Resolved},
        platform::Target,
    },
};

// Every shipped legacy surface except top-bar (quick-launch-panel shares the default capability and must be denied).
const OTHER_LABELS: &[&str] = &["bottom-bar", "quick-launch-panel", "task-gallery", "task-preview", "search-panel", "stack-popup",
    "process-manager", "control-plane", "settings-panel", "tray-panel", "terminal-panel", "command-panel", "audio-panel",
    "calendar-panel", "speech-history-panel", "speech-indicator", "context-menu-overlay", "quick-command-notification",
    "unknown", "future-panel", "snip-overlay-7-m0", "snip-preview-7"];
const NEW_COMMANDS: &[&str] = &["open_search_url", "run_search_quick_command", "copy_search_text"];

fn read(relative: &str) -> String {
    fs::read_to_string(PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(relative)).unwrap()
}

fn authority() -> (RuntimeAuthority, bool) {
    let manifests: BTreeMap<String, Manifest> =
        serde_json::from_str(&read("gen/schemas/acl-manifests.json")).unwrap();
    let capabilities: BTreeMap<String, Capability> =
        serde_json::from_str(&read("gen/schemas/capabilities.json")).unwrap();
    let resolved = Resolved::resolve(&manifests, capabilities, Target::Windows).unwrap();
    let enabled = resolved.has_app_acl;
    (RuntimeAuthority::new(manifests, resolved), enabled)
}

fn registered_commands() -> BTreeSet<String> {
    let source = read("src/main.rs");
    let list = source
        .split(".invoke_handler(tauri::generate_handler![")
        .nth(1)
        .expect("invoke handler inventory")
        .split("])")
        .next()
        .unwrap();
    list.split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(|s| s.rsplit("::").next().unwrap().to_owned())
        .collect()
}

#[test]
fn search_activation_commands_are_registered_and_granted_to_top_bar_only_among_unknown_labels() {
    let (authority, enabled) = authority();
    assert!(enabled);
    let registered = registered_commands();
    for command in NEW_COMMANDS {
        assert!(registered.contains(*command), "missing handler registration for {command}");
        assert!(
            authority.resolve_access(command, "top-bar", "top-bar", &Origin::Local).is_some(),
            "top-bar must be granted {command} by the generated ACL"
        );
        for label in OTHER_LABELS {
            assert!(
                authority.resolve_access(command, label, label, &Origin::Local).is_none(),
                "{label} gained {command}"
            );
        }
        let remote = Origin::Remote { url: "https://not-authorized.invalid/".parse().unwrap() };
        assert!(authority.resolve_access(command, "top-bar", "top-bar", &remote).is_none());
    }
}

#[test]
fn search_activation_commands_have_autogenerated_permission_files_and_contract_constants() {
    for command in NEW_COMMANDS {
        let permission = read(&format!("permissions/autogenerated/{command}.toml"));
        assert!(permission.contains(&format!("commands.allow = [\"{command}\"]")), "{command}");
    }
    let contracts = read("src/contracts.rs");
    assert!(contracts.contains("pub const COPY_SEARCH_TEXT: &str = \"copy_search_text\";"));
    assert!(contracts.contains("pub const OPEN_SEARCH_URL: &str = \"open_search_url\";"));
    assert!(contracts.contains("pub const RUN_SEARCH_QUICK_COMMAND: &str = \"run_search_quick_command\";"));
}

#[test]
fn search_activation_permissions_live_only_in_a_dedicated_top_bar_capability() {
    let dedicated: serde_json::Value = serde_json::from_str(&read("capabilities/search-top-bar.json")).unwrap();
    assert_eq!(dedicated["identifier"], "search-top-bar");
    assert_eq!(dedicated["windows"], serde_json::json!(["top-bar"]));
    let mut granted: Vec<String> = dedicated["permissions"].as_array().unwrap().iter().map(|p| p.as_str().unwrap().to_string()).collect();
    granted.sort();
    assert_eq!(granted, vec!["allow-copy-search-text", "allow-open-search-url", "allow-run-search-quick-command"]);
    // No shared capability may grant them (default.json also targets quick-launch-panel).
    for file in std::fs::read_dir(PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("capabilities")).unwrap() {
        let path = file.unwrap().path();
        if path.file_name().unwrap() == "search-top-bar.json" {
            continue;
        }
        let text = std::fs::read_to_string(&path).unwrap();
        for permission in ["allow-copy-search-text", "allow-open-search-url", "allow-run-search-quick-command"] {
            assert!(!text.contains(permission), "{permission} granted by {path:?}");
        }
    }
}
